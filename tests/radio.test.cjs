'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');

const read=file=>fs.readFileSync(path.join(__dirname,'..','js',file),'utf8');
const tracks=vm.runInNewContext(read('radio-data.js')+'\nRADIO_TRACKS', {});
const playerSource=read('radio-player.js');

class Element {
  constructor(id=''){
    this.id=id;this.dataset={};this.style={};this.attributes={};
    this.listeners={};this.hidden=false;this.value=id==='radioVol'?'80':'0';
    this.textContent='';this.innerHTML='';this.inert=false;
    this.children=[];this.classSet=new Set();
    this.classList={
      add:key=>this.classSet.add(key),
      remove:key=>this.classSet.delete(key),
      contains:key=>this.classSet.has(key),
      toggle:(key,value)=>{
        if(value===undefined)value=!this.classSet.has(key);
        if(value)this.classSet.add(key);else this.classSet.delete(key);
      }
    };
  }
  setAttribute(key,value){this.attributes[key]=String(value)}
  getAttribute(key){return this.attributes[key]??null}
  addEventListener(type,listener){(this.listeners[type]??=[]).push(listener)}
  dispatch(type,extra={}){
    for(const fn of this.listeners[type]||[])fn({
      type,target:this,stopPropagation(){},preventDefault(){},...extra
    });
  }
  querySelector(query){
    if(query==='.play-icon'||query==='.pause-icon')return {style:{}};
    if(query==='.rpl-select')return this.select||null;
    return null;
  }
  querySelectorAll(query){
    if(query==='.rpl-item')return this.rows||[];
    if(query==='.rpl-select')return this.selects||[];
    if(query==='.rpl-download')return this.downloads||[];
    return [];
  }
  before(item){this.status=item}
  appendChild(item){this.children.push(item);return item}
  remove(){}
  click(){this.dispatch('click');if(this.isLink)this.clicked=true}
  focus(){this.focused=true}
}

function page(storage=new Map(),fetchSuccess=true){
  const ids=['radioPanel','radioBackdrop','radioToggle','radioClose',
    'rPlay','rPrev','rNext','rShuffle','radioSeek','radioVol',
    'radioProgressFill','radioCurrTime','radioDuration','radioTrackName',
    'radioTrackArtist','radioTrackCount','radioArtImg','radioVinyl',
    'rpDot','radioLiveDot','radioPlaylist'];
  const elements=Object.fromEntries(ids.map(id=>[id,new Element(id)]));
  // Emulate the playlist DOM generated by innerHTML; code operates on 484 tracks.
  const playlist=elements.radioPlaylist;
  Object.defineProperty(playlist,'innerHTML',{
    get(){return this.html||''},
    set(value){
      this.html=value;
      if(!value)return;
      const count=(value.match(/class="rpl-item"/g)||[]).length;
      this.rows=Array.from({length:count},(_,i)=>{
        const e=new Element();e.dataset.idx=String(i);e.select=new Element();
        return e;
      });
      this.selects=Array.from({length:count},(_,i)=>{
        const e=new Element();e.dataset.idx=String(i);return e;
      });
      this.downloads=Array.from({length:count},(_,i)=>{
        const e=new Element();e.dataset.idx=String(i);return e;
      });
    }
  });
  const audioObjects=[],opened=[],links=[],revoked=[];
  class MockAudio {
    constructor(){
      this.src='';this.duration=230;this.currentTime=0;this.volume=.8;
      this.paused=true;this.listeners={};audioObjects.push(this);
    }
    addEventListener(type,fn){(this.listeners[type]??=[]).push(fn)}
    emit(type){for(const fn of this.listeners[type]||[])fn()}
    load(){this.currentTime=0;this.emit('loadedmetadata')}
    pause(){this.paused=true;this.emit('pause')}
    play(){this.paused=false;this.emit('play');return Promise.resolve()}
  }
  const document={
    getElementById(id){return elements[id]??null},
    createElement(tag){
      const element=new Element();
      if(tag==='a'){
        element.isLink=true;links.push(element);
        element.click=()=>{element.clicked=true};
      }
      return element;
    },
    body:new Element('body'),
    listeners:{},
    addEventListener(type,handler){(this.listeners[type]??=[]).push(handler)}
  };
  const events={};
  const window={
    addEventListener(type,fn){(events[type]??=[]).push(fn)},
    trigger(type){for(const fn of events[type]||[])fn()},
    open(url){opened.push(url);return {}},
    AfacesRadio:null
  };
  const sessionStorage={
    getItem:key=>storage.get(key)||null,
    setItem:(key,value)=>storage.set(key,value)
  };
  const fetch=async url=>{
    if(!fetchSuccess)throw new TypeError('CORS blocked');
    return {ok:true,blob:async()=>({size:16})};
  };
  const URL={
    createObjectURL:()=> 'blob:afaces-test',
    revokeObjectURL:url=>revoked.push(url)
  };
  const setTimeout=()=>0;
  vm.runInNewContext(playerSource,{RADIO_TRACKS:tracks,Audio:MockAudio,
    document,window,sessionStorage,fetch,URL,setTimeout,console,
    encodeURIComponent,Math,Number,String});
  return {tracks,elements,audio:audioObjects[0],api:window.AfacesRadio,
    window,storage,opened,links,revoked,playlist};
}

test('catálogo único de música Afaces con URLs y nombres válidos',()=>{
  assert.ok(tracks.length>=400);
  assert.equal(new Set(tracks.map(x=>x.path)).size,tracks.length);
  assert.ok(tracks.every(x=>x.path.startsWith('https://github.com/afaces/afaces.github.io/')&&x.path.endsWith('.mp3')));
  assert.ok(tracks.every(x=>x.name&&x.album&&x.vid));
});

test('todas las pistas tienen reproductor y botón de descarga accesibles',()=>{
  const app=page();
  assert.equal(app.playlist.rows.length,tracks.length);
  assert.equal(app.playlist.downloads.length,tracks.length);
  assert.match(app.playlist.innerHTML,/aria-label="Descargar MP3 \(descargar /);
  assert.match(app.playlist.innerHTML,/title="Descargar MP3 \(descargar /);
  assert.match(app.playlist.innerHTML,/<a class="rpl-download" /);
  assert.match(app.playlist.innerHTML,/m7 10 5 5 5-5/);
  assert.equal(app.elements.radioTrackName.textContent,tracks[0].name);
  assert.equal(app.elements.radioPanel.inert,true);
});

test('abrir panel, reproducir, siguiente, volumen, cierre sin interrumpir audio',async()=>{
  const app=page();
  app.elements.radioToggle.dispatch('click');
  assert.equal(app.elements.radioPanel.inert,false);
  assert.equal(app.elements.radioToggle.getAttribute('aria-expanded'),'true');
  app.elements.rPlay.dispatch('click');
  await Promise.resolve();
  assert.equal(app.api.getState().playing,true);
  app.elements.rNext.dispatch('click');
  await Promise.resolve();
  assert.equal(app.api.getState().index,1);
  assert.equal(app.audio.src,tracks[1].path);
  app.elements.radioVol.value='25';
  app.elements.radioVol.dispatch('input');
  assert.equal(app.audio.volume,.25);
  app.elements.radioClose.dispatch('click');
  assert.equal(app.elements.radioPanel.inert,true);
  assert.equal(app.api.getState().playing,true);
});

test('al terminar una pista avanza y mantiene reproducción aunque paused ya sea true',async()=>{
  const app=page();
  app.elements.rPlay.dispatch('click');
  await Promise.resolve();
  assert.equal(app.api.getState().playing,true);
  // HTMLMediaElement marca paused=true al alcanzar el final.
  app.audio.pause();
  assert.equal(app.api.getState().playing,false);
  app.audio.emit('ended');
  await Promise.resolve();
  assert.equal(app.api.getState().index,1);
  assert.equal(app.api.getState().playing,true);
});

test('restauración de pista y tiempo en nueva página sin autoplay',()=>{
  const storage=new Map();
  const first=page(storage);
  first.api.select(7,false);
  first.audio.currentTime=44;
  first.window.trigger('pagehide');
  const next=page(storage);
  assert.equal(next.api.getState().index,7);
  assert.equal(next.audio.currentTime,44);
  assert.equal(next.audio.paused,true);
  assert.equal(next.api.getState().playing,false);
});

test('cada descarga enlaza directamente al MP3 original en una pestaña separada',()=>{
  const app=page();
  const html=app.playlist.innerHTML;
  const links=[...html.matchAll(/<a class="rpl-download" ([^>]+)>/g)];
  assert.equal(links.length,tracks.length);
  for(const index of [0,2,Math.floor(tracks.length/2),tracks.length-1]){
    const attributes=links[index][1];
    const escape=value=>String(value).replace(/[&<>"']/g,c=>({
      '&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'
    })[c]);
    assert.ok(attributes.includes('href="'+escape(tracks[index].path)+'"'));
    assert.ok(attributes.includes('target="_blank"'));
    assert.ok(attributes.includes('rel="noopener noreferrer"'));
    assert.ok(attributes.includes('title="Descargar MP3 (descargar '+escape(tracks[index].name)+')"'));
    assert.ok(attributes.includes('aria-label="Descargar MP3 (descargar '+escape(tracks[index].name)+')"'));
  }
  assert.equal(app.api.getState().playing,false);
  assert.equal(app.links.length,0); // No hay link artificial, fetch ni Blob.
});

